"""
Unit and boundary tests for XYZ Point Cloud Parser module (xyz_parser.py).
"""

import numpy as np
import pytest

from xyz_parser import XYZCloudData, load_xyz_file


def create_sample_xyz_file(filepath, points) -> None:
    """Utility helper to write XYZ points array to file."""
    with open(filepath, "w", encoding="utf-8") as f:
        for p in points:
            f.write(" ".join(str(v) for v in p) + "\n")


def test_load_xyz_basic(tmp_path) -> None:
    """Test reading basic valid 3D points without origin shift."""
    xyz_file = tmp_path / "sample.xyz"
    raw_points = [
        [0.0, 0.0, 10.0],
        [10.0, 0.0, 20.0],
        [0.0, 10.0, 15.0],
        [10.0, 10.0, 25.0],
    ]
    create_sample_xyz_file(xyz_file, raw_points)

    data = load_xyz_file(str(xyz_file), auto_clean_outliers=False, center_to_origin=False)

    assert isinstance(data, XYZCloudData)
    assert len(data.points) == 4
    assert data.xmin == 0.0
    assert data.xmax == 10.0
    assert data.ymin == 0.0
    assert data.ymax == 10.0
    assert data.zmin == 10.0
    assert data.zmax == 25.0
    assert data.width_m == 10.0
    assert data.height_m == 10.0
    assert data.depth_m == 15.0
    assert data.origin_offset == (0.0, 0.0, 0.0)


def test_load_xyz_center_to_origin(tmp_path) -> None:
    """Test 3D point centering to world origin (0, 0, 0) including Z base alignment."""
    xyz_file = tmp_path / "centered.xyz"
    raw_points = [
        [100.0, 200.0, 10.0],
        [110.0, 220.0, 30.0],
    ]
    create_sample_xyz_file(xyz_file, raw_points)

    data = load_xyz_file(str(xyz_file), auto_clean_outliers=False, center_to_origin=True)

    assert data.origin_offset == (105.0, 210.0, 10.0)
    assert np.isclose(data.xmin, -5.0)
    assert np.isclose(data.xmax, 5.0)
    assert np.isclose(data.ymin, -10.0)
    assert np.isclose(data.ymax, 10.0)
    assert np.isclose(data.zmin, 0.0)
    assert np.isclose(data.zmax, 20.0)
    assert np.isclose(data.depth_m, 20.0)


def test_xyz_cloud_data_immutability(tmp_path) -> None:
    """Verify XYZCloudData is frozen and underlying NumPy array is read-only."""
    xyz_file = tmp_path / "immutable.xyz"
    create_sample_xyz_file(xyz_file, [[0.0, 0.0, 1.0], [5.0, 5.0, 2.0]])
    data = load_xyz_file(str(xyz_file))

    with pytest.raises(AttributeError):
        data.xmin = -999.0  # type: ignore[misc]

    with pytest.raises(ValueError, match="read-only"):
        data.points[0, 0] = 999.0


def test_load_pts_with_count_header_and_extra_columns(tmp_path) -> None:
    """Test reading a 7-column .pts file (X Y Z Intensity R G B) with leading point count."""
    pts_file = tmp_path / "scan.pts"
    pts_file.write_text(
        "3\n"
        "0.0 0.0 5.0 -1200 255 128 64\n"
        "10.0 0.0 15.0 -1150 200 100 50\n"
        "0.0 20.0 25.0 -1100 180 90 40\n",
        encoding="utf-8",
    )

    data = load_xyz_file(str(pts_file), center_to_origin=False)
    assert len(data.points) == 3
    assert data.width_m == 10.0
    assert data.height_m == 20.0
    assert data.zmin == 5.0
    assert data.zmax == 25.0


def test_load_xyz_uniform_multicolumn_fast_path(tmp_path) -> None:
    """Verify uniform 4-column whitespace files do not scramble columns across rows."""
    xyz_file = tmp_path / "four_col.xyz"
    create_sample_xyz_file(
        xyz_file,
        [
            [1.0, 2.0, 10.0, 999.0],
            [5.0, 8.0, 20.0, 888.0],
        ],
    )

    data = load_xyz_file(str(xyz_file), center_to_origin=False)
    assert len(data.points) == 2
    assert np.allclose(data.points[0], [1.0, 2.0, 10.0])
    assert np.allclose(data.points[1], [5.0, 8.0, 20.0])


