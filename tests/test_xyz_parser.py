def test_load_xyz_manual_height_filter_and_single_bound(tmp_path) -> None:
    """Test min/max elevation threshold filtering (both bounds and single bound)."""
    xyz_file = tmp_path / "filtered.xyz"
    raw_points = [
        [0.0, 0.0, -100.0],
        [1.0, 1.0, 50.0],
        [2.0, 2.0, 100.0],
        [3.0, 3.0, 999.0],
    ]
    create_sample_xyz_file(xyz_file, raw_points)

    data = load_xyz_file(
        str(xyz_file),
        min_height=0.0,
        max_height=200.0,
        auto_clean_outliers=False,
        center_to_origin=False,
    )
    assert len(data.points) == 2
    assert data.zmin == 50.0
    assert data.zmax == 100.0

    data_min_only = load_xyz_file(str(xyz_file), min_height=0.0, center_to_origin=False)
    assert len(data_min_only.points) == 3
    assert data_min_only.zmin == 50.0


def test_load_xyz_auto_outlier_cleaning_large_cloud(tmp_path) -> None:
    """Test automatic 0.1% - 99.9% percentile outlier removal on clouds with >= 100 points."""
    xyz_file = tmp_path / "outliers.xyz"
    pts = [[float(i), float(i), 50.0] for i in range(1000)]
    pts[0][2] = -5000.0  # Extreme low spike
    pts[-1][2] = 9000.0  # Extreme high spike
    create_sample_xyz_file(xyz_file, pts)

    data = load_xyz_file(str(xyz_file), auto_clean_outliers=True, center_to_origin=False)
    assert len(data.points) == 998
    assert data.zmin == 50.0
    assert data.zmax == 50.0


def test_load_xyz_negative_and_boundary_errors(tmp_path) -> None:
    """Test explicit failure modes for missing, empty, malformed, NaN, and degenerate inputs."""
    with pytest.raises(FileNotFoundError):
        load_xyz_file("non_existent_file.xyz")

    empty_file = tmp_path / "empty.xyz"
    empty_file.write_text("   \n  ", encoding="utf-8")
    with pytest.raises(ValueError, match="is empty"):
        load_xyz_file(str(empty_file))

    comments_only = tmp_path / "comments.xyz"
    comments_only.write_text("# only comment\n// another comment\n", encoding="utf-8")
    with pytest.raises(ValueError, match="no valid 3D XYZ"):
        load_xyz_file(str(comments_only))

    malformed_file = tmp_path / "malformed.xyz"
    malformed_file.write_text("0.0 0.0 1.0\n1.0 bad_float 2.0\n", encoding="utf-8")
    with pytest.raises(ValueError, match="Malformed coordinate data on line 2"):
        load_xyz_file(str(malformed_file))

    too_few_cols = tmp_path / "two_cols.xyz"
    too_few_cols.write_text("0.0 0.0 1.0\n5.0 6.0\n", encoding="utf-8")
    with pytest.raises(ValueError, match="at least 3"):
        load_xyz_file(str(too_few_cols))

    nan_file = tmp_path / "nan.xyz"
    nan_file.write_text("0.0 0.0 nan\n1.0 1.0 2.0\n", encoding="utf-8")
    with pytest.raises(ValueError, match="non-finite"):
        load_xyz_file(str(nan_file))

    valid_file = tmp_path / "valid.xyz"
    create_sample_xyz_file(valid_file, [[0.0, 0.0, 10.0], [5.0, 5.0, 20.0]])
    with pytest.raises(ValueError, match="must be strictly less than"):
        load_xyz_file(str(valid_file), min_height=100.0, max_height=50.0)

    with pytest.raises(ValueError, match="No points remain"):
        load_xyz_file(str(valid_file), min_height=500.0, max_height=600.0)

    coincident_file = tmp_path / "coincident.xyz"
    create_sample_xyz_file(coincident_file, [[1.0, 2.0, 10.0], [1.0, 2.0, 20.0]])
    with pytest.raises(ValueError, match="zero physical width and height"):
        load_xyz_file(str(coincident_file))
